const assert=require('node:assert/strict'),M=require('../web/listening-model.js');
const said='Привет! Как дела? Я хочу сказать тебе спасибо за всё, что ты делаешь.';
let c=M.compare(said,'привет как дела я хочу сказать тебе спасибо за все что ты делаешь');
assert.equal(c.percent,100,'case, punctuation and ё/е do not count against you');
assert.equal(c.total,13);
c=M.compare(said,'привет как дела я хочу сказать тебе спасибо');
assert.equal(c.words.filter(w=>w.state==='missed').length,5,'words that were never written are missed');
assert.equal(c.percent,Math.round(8/13*100));
c=M.compare('Я люблю твою улыбку','я люблю твоя улыбка');
assert.deepEqual(c.words.map(w=>w.state),['right','right','close','close'],'a wrong ending is close, not wrong');
assert.ok(c.percent>=75&&c.percent<100);
c=M.compare('Мы идём в магазин','мы идём в школу');
assert.deepEqual(c.words.map(w=>w.state),['right','right','right','wrong'],'a different word is wrong');
assert.equal(c.words[3].written,'школу');
c=M.compare('Как дела','как у тебя дела');
assert.deepEqual(c.words.map(w=>w.state),['right','right']);assert.deepEqual(c.extra,['у','тебя'],'extra words are listed');
assert.equal(M.compare('','').percent,0);
assert.equal(M.normalize('вода́'),'вода','stress marks are ignored');
assert.deepEqual(M.toLearn(M.compare('Я люблю твою улыбку','я люблю')),['твою','улыбку']);
console.log('PASS: listening checks — right, close (endings), wrong, missed and extra words, and ё/stress/punctuation ignored.');
